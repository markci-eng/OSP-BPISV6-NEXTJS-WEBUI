/** Reverse the line format above into the rows the table actually holds. */
function parse(table: string): RefMortuaryCSPRateRecord[] {
  const rows: RefMortuaryCSPRateRecord[] = [];
  // Split on either line ending: the file is committed LF but a checkout on a
  // Windows box with `core.autocrlf` on hands this string back with CRLF, and a
  // stray `\r` would ride along on the last amount of every line.
  for (const line of table.trim().split(/\r?\n/)) {
    const split = line.indexOf("|");
    const mortCode = line.slice(0, split);
    for (const pair of line.slice(split + 1).split(" ")) {
      const colon = pair.indexOf(":");
      rows.push({
        mortCode,
        cspCode: pair.slice(0, colon),
        cspAmount: Number(pair.slice(colon + 1)),
      });
    }
  }
  return rows;
}

