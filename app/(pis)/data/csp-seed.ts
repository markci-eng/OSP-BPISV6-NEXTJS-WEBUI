/* =========================== RefMortuaryCSPRate =========================== */
//
// 7,985 rows, 840 mortuaries, 23 of the 47 codes above — the whole table as it
// was dropped on 2026-08-26, loaded verbatim.
//
// WRITTEN AS TEXT AND GROUPED BY MORTUARY, which is the one liberty taken with
// it and it is a liberty of LAYOUT, not of content. The drop is one row per
// line — `BT1-00|FE|15000.00` — and the mortuary code repeats on nine and a half
// lines out of ten. Collapsing those onto one line per mortuary turns 7,985
// lines into 840 and 164KB into 78KB; no value is normalised, rounded, filled in
// or dropped, and `parse` below reverses it exactly. Grep for a mortuary code
// here and you get its whole rate card on one line, which reading 7,985 object
// literals would not have given either.
//
// The decimals ARE dropped, and that is not a liberty: every amount on file ends
// in `.00`, `CSPAmount` is money in whole pesos, and `15000.00` and `15000` are
// the same number to anything that reads this.
//
// TWO THINGS IN IT ARE ODD AND BOTH ARE LEFT ALONE, for the reason the mortuary
// table's unresolved chapel codes are:
//
//   A CODE WITH A SPACE IN IT. "MD 3", one row, `SH`. There is no such mortuary;
//   MD3-… codes exist and this is plainly one of them mistyped. Which one is not
//   this layer's call, so it is carried exactly as given.
//
//   420 CODES THAT NAME NO MORTUARY. GM1-01, GM3-45, CLBZ3-02 and the rest have
//   rates here and no row in `RefMortuary` — half this table prices funeral homes
//   the mortuary reference does not list. Nothing is invented to meet them; the
//   lookup simply finds no mortuary, and a mortuary drop that names them fixes it
//   without touching code.
//
// AND THE TABLE IS SPARSE the other way too. Of the 424 mortuaries that ARE on
// file, 172 have no rate for at least one of the eleven plans in `planTypeSeed`;
// ten of those price none of the eleven, and four of THOSE have no row in this
// table at all — CLAIMS-00 (which is the "NO BILLING MORTUARY" row), MD1-36,
// MD3-24 and SL3-11. That is a rate card with a plan missing from it rather than
// a hole in the drop, and it is why the lookup answers "nothing" and not zero —
// see `RefMortuaryCSPRateRecord`.

